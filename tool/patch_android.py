#!/usr/bin/env python3
"""Patches the generated android/ project for Fyleon. Safe to run many times.

- app label, permissions, AdMob application id (from config/fyleon_config.json)
- minSdk >= 24
- verifies applicationId == com.fyleon.app
No secrets are read or written here.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "android/app/src/main/AndroidManifest.xml"
TEST_APP_ID = "ca-app-pub-3940256099942544~3347511713"
WANTED_ID = "com.fyleon.app"
APP_LABEL = "Fyleon"

# R8 (code shrinking) removed the constructor of androidx.work.impl.WorkDatabase_Impl
# (WorkManager/Room, pulled in by AdMob) and the app crashed at launch:
#   "Failed to create an instance of androidx.work.impl.WorkDatabase"
PROGUARD_RULES = """# Generated by tool/patch_android.py - do not edit by hand.
# Room/WorkManager (used by the AdMob SDK) create the database class by reflection.
-keep class * extends androidx.room.RoomDatabase { <init>(); }
-keep class androidx.work.impl.WorkDatabase { *; }
-keep class androidx.work.impl.WorkDatabase_Impl { *; }
-keep class androidx.work.** { *; }
-dontwarn androidx.room.**
-dontwarn androidx.work.**
"""


def fail(msg):
    print("PATCH ERROR:", msg)
    sys.exit(1)


def load_config():
    try:
        return json.loads((ROOT / "config/fyleon_config.json").read_text("utf-8"))
    except Exception as e:  # noqa
        print("config not readable, using defaults:", e)
        return {}


def set_permission(text, name, present, attrs=""):
    full = f"android.permission.{name}" if "." not in name else name
    pattern = re.compile(r'[ \t]*<uses-permission\b[^>]*android:name="' + re.escape(full) + r'"[^>]*/>[ \t]*\n?')
    text = pattern.sub("", text)
    if present:
        line = f'\n    <uses-permission android:name="{full}"{(" " + attrs) if attrs else ""}/>'
        text = re.sub(r"(<manifest\b[^>]*>)", lambda m: m.group(1) + line, text, count=1)
    return text


def patch_manifest(cfg):
    if not MANIFEST.exists():
        fail(f"{MANIFEST} not found. Run 'flutter create --platforms=android .' first.")
    text = MANIFEST.read_text("utf-8")

    admob = cfg.get("admob") or {}
    use_test = admob.get("useTestAds", True) is not False
    app_id = ((admob.get("android") or {}).get("appId") or "").strip()
    if use_test or not app_id:
        app_id = TEST_APP_ID
    all_files = bool((cfg.get("features") or {}).get("allFilesAccess", False))

    text = set_permission(text, "INTERNET", True)
    text = set_permission(text, "ACCESS_NETWORK_STATE", True)
    text = set_permission(text, "com.google.android.gms.permission.AD_ID", True)
    text = set_permission(text, "MANAGE_EXTERNAL_STORAGE", all_files)
    text = set_permission(text, "READ_EXTERNAL_STORAGE", all_files, 'android:maxSdkVersion="32"')

    # app label
    text = re.sub(r'(<application\b[^>]*?android:label=")[^"]*(")', r"\g<1>" + APP_LABEL + r"\2", text, count=1)

    # AdMob application id
    meta = (
        '\n        <meta-data'
        '\n            android:name="com.google.android.gms.ads.APPLICATION_ID"'
        f'\n            android:value="{app_id}"/>'
    )
    if "com.google.android.gms.ads.APPLICATION_ID" in text:
        text = re.sub(
            r'(com\.google\.android\.gms\.ads\.APPLICATION_ID"\s*android:value=")[^"]*(")',
            r"\g<1>" + app_id + r"\2",
            text,
            count=1,
        )
    else:
        text = re.sub(r"(<application\b[^>]*>)", lambda m: m.group(1) + meta, text, count=1)

    MANIFEST.write_text(text, "utf-8")
    print(f"manifest ok (test ads: {use_test or app_id == TEST_APP_ID}, allFilesAccess: {all_files})")


def patch_gradle():
    gradle = None
    for name in ("build.gradle.kts", "build.gradle"):
        f = ROOT / "android/app" / name
        if f.exists():
            gradle = f
            break
    if gradle is None:
        fail("android/app/build.gradle(.kts) not found")
    text = gradle.read_text("utf-8")

    m = re.search(r'applicationId\s*=?\s*"([^"]+)"', text)
    if not m or m.group(1) != WANTED_ID:
        fail(f"applicationId is {m.group(1) if m else 'missing'}, expected {WANTED_ID}")

    def bump(match):
        value = match.group(3)
        if value.isdigit() and int(value) >= 24:
            return match.group(0)
        if value == "flutter.minSdkVersion":
            return match.group(0)
        return f"{match.group(1)}{match.group(2)}24"

    text = re.sub(r"(minSdk(?:Version)?)(\s*=\s*|\s+)(flutter\.minSdkVersion|\d+)", bump, text)

    # keep rules file must be referenced from the release build type
    if "proguard-rules.pro" not in text:
        if gradle.suffix == ".kts":
            line = '\n            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")'
        else:
            line = "\n            proguardFiles getDefaultProguardFile('proguard-android-optimize.txt'), 'proguard-rules.pro'"
        text, n = re.subn(r"(buildTypes\s*\{\s*release\s*\{)", lambda m: m.group(1) + line, text, count=1)
        if n == 0:
            print("WARNING: could not find buildTypes { release { in", gradle.name)
    # AGP 9 rejects the old default file ("includes -dontoptimize") -> use the optimize variant.
    text = text.replace("proguard-android.txt", "proguard-android-optimize.txt")
    gradle.write_text(text, "utf-8")
    (ROOT / "android/app/proguard-rules.pro").write_text(PROGUARD_RULES, "utf-8")
    print("gradle ok:", gradle.name, "applicationId", WANTED_ID, "+ proguard-rules.pro")


NSC_XML = """<?xml version="1.0" encoding="utf-8"?>
<network-security-config>
    <!-- Fyleon's web preview serves your project files from a tiny server that lives
         only on this device (127.0.0.1). Plain HTTP is allowed for these two hosts only. -->
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">127.0.0.1</domain>
        <domain includeSubdomains="false">localhost</domain>
    </domain-config>
</network-security-config>
"""


def patch_network_security():
    res = ROOT / "android/app/src/main/res/xml"
    res.mkdir(parents=True, exist_ok=True)
    (res / "network_security_config.xml").write_text(NSC_XML, "utf-8")
    text = MANIFEST.read_text("utf-8")
    if "android:networkSecurityConfig" not in text:
        text = re.sub(
            r"(<application\b)",
            r'\1\n        android:networkSecurityConfig="@xml/network_security_config"',
            text,
            count=1,
        )
        MANIFEST.write_text(text, "utf-8")
    print("network security config ok")


INTENT_SNIPPET = """
            <!-- fyleon-intents: Fyleon shows up in Open with / Share / Send to -->
            <intent-filter>
                <action android:name="android.intent.action.VIEW"/>
                <category android:name="android.intent.category.DEFAULT"/>
                <category android:name="android.intent.category.BROWSABLE"/>
                <data android:scheme="content"/>
                <data android:scheme="file"/>
                <data android:mimeType="*/*"/>
            </intent-filter>
            <intent-filter>
                <action android:name="android.intent.action.SEND"/>
                <category android:name="android.intent.category.DEFAULT"/>
                <data android:mimeType="*/*"/>
            </intent-filter>
            <intent-filter>
                <action android:name="android.intent.action.SEND_MULTIPLE"/>
                <category android:name="android.intent.category.DEFAULT"/>
                <data android:mimeType="*/*"/>
            </intent-filter>
        """


def patch_intents_and_activity():
    text = MANIFEST.read_text("utf-8")
    if "fyleon-intents" not in text:
        m = re.search(r'android:name="\.MainActivity"', text)
        if m:
            end = text.find("</activity>", m.end())
            if end != -1:
                text = text[:end] + INTENT_SNIPPET + text[end:]
                MANIFEST.write_text(text, "utf-8")
        else:
            print("WARNING: .MainActivity not found in the manifest, intent filters skipped")
    # native side: replace the generated MainActivity with ours
    kotlin_root = ROOT / "android/app/src/main/kotlin"
    targets = list(kotlin_root.rglob("MainActivity.kt")) if kotlin_root.exists() else []
    src = (ROOT / "tool/templates/MainActivity.kt").read_text("utf-8")
    if not targets:
        dest = kotlin_root / "com/fyleon/app/MainActivity.kt"
        dest.parent.mkdir(parents=True, exist_ok=True)
        targets = [dest]
    for t in targets:
        t.write_text(src, "utf-8")
    print("intent filters + MainActivity ok")


def patch_gradle_properties(cfg):
    """build.shrinkCode=false in the config -> android/gradle.properties gets shrink=false
    (same effect as `flutter build --no-shrink`: R8 off). Default: R8 off until the keep rules
    are verified by the smoke test."""
    props = ROOT / "android/gradle.properties"
    if not props.exists():
        return
    shrink = (cfg.get("build") or {}).get("shrinkCode", False) is True
    lines = [l for l in props.read_text("utf-8").splitlines() if not l.strip().startswith("shrink=")]
    if not shrink:
        lines.append("shrink=false")
    props.write_text("\n".join(lines) + "\n", "utf-8")
    print("gradle.properties ok: shrink", "ON" if shrink else "OFF")


if __name__ == "__main__":
    _cfg = load_config()
    patch_manifest(_cfg)
    patch_gradle()
    patch_gradle_properties(_cfg)
    patch_network_security()
    patch_intents_and_activity()
